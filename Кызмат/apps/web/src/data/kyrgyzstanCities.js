export function getCityOptions(selectedCity = "") {
  if (!selectedCity || kyrgyzstanCities.includes(selectedCity)) {
    return kyrgyzstanCities;
  }

  return [selectedCity, ...kyrgyzstanCities];
}

export function getLocalizedCityOptions(selectedCity = "", language = "ru") {
  return getCityOptions(selectedCity).map((city) => ({
    value: city,
    label: translateCityName(city, language),
  }));
}
