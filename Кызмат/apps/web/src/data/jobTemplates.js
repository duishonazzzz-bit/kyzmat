function normalizeCategoryName(name) {
  return String(name || "").trim().toLowerCase();
}

function findTemplateGroupForCategory(name) {
  const normalized = normalizeCategoryName(name);

  return (
    jobTemplateCatalog.find((group) => group.matchers.some((matcher) => normalized.includes(matcher))) || null
  );
}

export function buildTemplateSections(categories) {
  return jobTemplateCatalog
    .map((group) => {
      const category = (categories || []).find((item) =>
        group.matchers.some((matcher) => normalizeCategoryName(item.name).includes(matcher)),
      );

      if (!category) {
        return null;
      }

      return {
        ...group,
        categoryId: String(category.id),
        categoryName: category.name,
      };
     
    })
    .filter(Boolean);
}

export function findTemplateSectionByCategoryId(categories, categoryId) {
  const category = (categories || []).find((item) => String(item.id) === String(categoryId));

  if (!category) {
    return null;
  }

  const group = findTemplateGroupForCategory(category.name);
  if (!group) {
    return null;
  }

  return {
    ...group,
    categoryId: String(category.id),
    categoryName: category.name,
  };
}

export function formatDueDateFromNow(days) {
  const date = new Date();
  date.setDate(date.getDate() + Number(days || 0));
  return date.toISOString().slice(0, 10);
}
